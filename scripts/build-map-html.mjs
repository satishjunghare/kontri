// Builds src/map/mapHtml.ts: one self-contained HTML page (Leaflet + our map logic) as a string.
// Run with `npm run build:map` after changing scripts/map-page.* or upgrading leaflet.
import { readFileSync, writeFileSync } from 'node:fs';

const leafletJs = readFileSync('node_modules/leaflet/dist/leaflet.js', 'utf8');
const leafletCss = readFileSync('node_modules/leaflet/dist/leaflet.css', 'utf8');
const pageJs = readFileSync('scripts/map-page.js', 'utf8');
const pageCss = readFileSync('scripts/map-page.css', 'utf8');
for (const [name, text] of [['leaflet.js', leafletJs], ['map-page.js', pageJs]]) {
  if (/<\/script/i.test(text)) throw new Error(`${name} contains a closing script tag`);
}

const html = `<!doctype html>
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>${leafletCss}
${pageCss}</style></head>
<body><div id="map"></div><div id="banner">Map tiles can't load. Check your internet connection. Your stops are still shown.</div>
<script>${leafletJs}</script>
<script>${pageJs}</script>
</body></html>`;

writeFileSync(
  'src/map/mapHtml.ts',
  `// GENERATED by scripts/build-map-html.mjs. Do not edit by hand; run \`npm run build:map\`.\n` +
    `// Leaflet 1.9 (BSD-2-Clause, https://leafletjs.com) plus the map page logic, as one HTML page.\n` +
    `export const MAP_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`Wrote src/map/mapHtml.ts (${Math.round(html.length / 1024)} KB)`);
